// Helper for generating safe WhatsApp URLs
export function getWhatsAppUrl(customText?: string): string | null {
  if (!siteConfig.whatsapp || siteConfig.whatsapp.trim() === "" || siteConfig.whatsapp === "WHATSAPP_NUMBER") {
    return null;
  }
  const cleanNumber = siteConfig.whatsapp.replace(/[^0-9]/g, "");
  const defaultText = "السلام عليكم ورحمة الله، أرغب في الاستفسار عن خدمات النجارة والأثاث.";
  const encodedText = encodeURIComponent(customText || defaultText);
  return `https://wa.me/${cleanNumber}?text=${encodedText}`;
}

// Helper for generating safe Phone URLs
export function getPhoneUrl(): string | null {
  if (!siteConfig.phone || siteConfig.phone.trim() === "" || siteConfig.phone === "PHONE_NUMBER") {
    return null;
  }
  const cleanNumber = siteConfig.phone.replace(/[^0-9+]/g, "");
  return `tel:${cleanNumber}`;
}

